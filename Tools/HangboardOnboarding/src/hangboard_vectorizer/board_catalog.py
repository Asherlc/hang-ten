def _render_swift_hold(hold: BoardHold) -> list[str]:
    properties = [
        f"                id: {_swift_string_literal(hold.id)}",
        f"                name: {_swift_string_literal(hold.name)}",
        f"                shortLabel: {_swift_string_literal(hold.short_label)}",
        f"                detail: {_swift_string_literal(hold.detail)}",
        f"                kind: .{hold.kind}",
        (
            "                frame: HoldFrame("
            f"x: {_format_swift_number(hold.frame.x)}, "
            f"y: {_format_swift_number(hold.frame.y)}, "
            f"width: {_format_swift_number(hold.frame.width)}, "
            f"height: {_format_swift_number(hold.frame.height)})"
        ),
    ]
    if hold.size_mm is not None:
        properties.append(f"                sizeMillimeters: {hold.size_mm}")
    if hold.grip_type is not None:
        properties.append(f"                gripType: .{hold.grip_type}")
    if hold.features:
        features = ", ".join(f".{feature}" for feature in hold.features)
        properties.append(f"                features: [{features}]")
    lines = ["            BoardHold("]
    for property_index, property_line in enumerate(properties):
        suffix = "," if property_index != len(properties) - 1 else ""
        lines.append(f"{property_line}{suffix}")
    lines.append("            ),")
    return lines


def _format_swift_number(value: float) -> str:
    return format(value, ".3f").rstrip("0").rstrip(".")


def _swift_string_literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _estimate_region_count(run_root: Path) -> int:
    manifest_path = run_root / "stages" / "04" / "attempt-0001" / "stage-4-manifest.json"
    if not manifest_path.exists():
        return 0
    manifest = _load_json_payload(manifest_path, str(manifest_path))
    return len(_required_list(manifest, "regions", str(manifest_path)))


def canonicalize_region_key(value: str) -> str:
    match = re.fullmatch(r"(.*)-(\d+)-(.*)", value)
    if not match:
        return value
    prefix, digit, suffix = match.groups()
    if digit not in _FINGER_WORDS:
        return value
    return f"{prefix}-{_FINGER_WORDS[digit]}-{suffix}"


def _validate_and_count_regions(run_root: Path, board: BoardDocument) -> int:
    run_manifest = _load_json_payload(run_root / "run.json", str(run_root / "run.json"))
    stages = _required_list(run_manifest, "stages", str(run_root / "run.json"))
    stage4_records = [stage for stage in stages if isinstance(stage, Mapping) and stage.get("stage") == 4]
    if not stage4_records:
        raise ValueError("complete onboarding run is missing stage 4")
    stage4 = stage4_records[-1]
    artifact_root = _required_str(stage4, "artifactRoot", "run manifest stage 4 artifactRoot")
    if Path(artifact_root).is_absolute() or ".." in Path(artifact_root).parts:
        raise ValueError("run manifest stage 4 artifactRoot must be a safe relative path")
    manifest_path = run_root / artifact_root / "stage-4-manifest.json"
    stage4_manifest = _load_json_payload(manifest_path, str(manifest_path))
    regions = _required_list(stage4_manifest, "regions", str(manifest_path))

    hold_by_region = {hold.region_id: hold.id for hold in board.holds if hold.region_id is not None}
    if len(hold_by_region) != len(board.holds):
        raise ValueError("all holds must include regionId for approved onboarding run registration")

    seen_region_ids: set[int] = set()
    for index, region in enumerate(regions):
        if not isinstance(region, Mapping):
            raise ValueError(f"{manifest_path}.regions[{index}] must be an object")
        region_id = _required_int(region, "id", f"{manifest_path}.regions[{index}].id")
        if region_id in seen_region_ids:
            raise ValueError(f"duplicate stage-4 region id {region_id}")
        seen_region_ids.add(region_id)
        key = _required_str(region, "key", f"{manifest_path}.regions[{index}].key")
        hold_id = hold_by_region.get(region_id)
        if hold_id is None:
            raise ValueError(f"run region id {region_id} has no matching hold on board")
        if canonicalize_region_key(key) != hold_id:
            raise ValueError(
                f"run region id {region_id} maps to {key!r} which does not match board hold {hold_id!r}"
            )

    if len(seen_region_ids) != len(hold_by_region):
        raise ValueError("run region count does not match board hold count")
    return len(seen_region_ids)
