@dataclass
class CatalogBoardEntry:
    id: str
    path: str
    lifecycle: str

    @classmethod
    def from_json(cls, payload: Mapping[str, Any], source: str) -> "CatalogBoardEntry":
        board_id = _required_str(payload, "id", f"{source}.id")
        board_path = _required_str(payload, "path", f"{source}.path")
        lifecycle = _required_str(payload, "lifecycle", f"{source}.lifecycle")
        if lifecycle not in _LIFECYCLES:
            raise ValueError(
                f"{source}.lifecycle must be one of {_LIFECYCLES}, got {lifecycle!r}"
            )
        _require_identifier(board_id, "board id")
        if board_path.startswith("/") or ".." in Path(board_path).parts:
            raise ValueError(f"{source}.path must be a relative path inside the catalog")
        return cls(board_id, board_path, lifecycle)

    def to_json(self) -> dict[str, object]:
        return {"id": self.id, "path": self.path, "lifecycle": self.lifecycle}


@dataclass
class CatalogDocument:
    boards: list[CatalogBoardEntry]
    schema_version: int = _CATALOG_SCHEMA_VERSION

    @classmethod
    def from_json(
        cls, payload: Mapping[str, Any], source: str
    ) -> "CatalogDocument":
        schema_version = _required_int(payload, "schemaVersion", f"{source}.schemaVersion")
        if schema_version != _CATALOG_SCHEMA_VERSION:
            raise ValueError(
                f"{source}.schemaVersion must be {_CATALOG_SCHEMA_VERSION}, got {schema_version!r}"
            )
        entries = _required_list(payload, "boards", f"{source}.boards")
        parsed = [
            CatalogBoardEntry.from_json(raw, f"{source}.boards[{index}]")
            for index, raw in enumerate(entries)
        ]
        return cls(boards=parsed, schema_version=schema_version)

    def to_json(self) -> dict[str, object]:
        return {
            "schemaVersion": self.schema_version,
            "boards": [board.to_json() for board in self.boards],
        }


